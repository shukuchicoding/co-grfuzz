"""Numerically safe GRPO helpers that do not depend on TensorFlow.

Keeping sampling and group-normalization here makes their edge-case behavior easy
to test independently from the neural-network runtime.
"""

from __future__ import annotations

import math
from typing import Optional, Tuple

import numpy as np

EPS = 1e-8


def probabilities_from_log_probs(log_probs) -> np.ndarray:
    """Convert 1-D log-probabilities/logits to a valid probability vector.

    The function is intentionally defensive:
    - empty input -> empty output;
    - finite values are normalized with a max-shift to avoid overflow;
    - if every value is non-finite or the normalization degenerates, fall back
      to a uniform distribution so fuzzing can continue safely.
    """
    values = np.asarray(log_probs, dtype=np.float64).reshape(-1)
    if values.size == 0:
        return np.asarray([], dtype=np.float64)

    finite = np.isfinite(values)
    if not finite.any():
        return np.full(values.size, 1.0 / values.size, dtype=np.float64)

    max_value = np.max(values[finite])
    weights = np.zeros(values.size, dtype=np.float64)
    weights[finite] = np.exp(values[finite] - max_value)
    total = float(weights.sum())

    if not math.isfinite(total) or total <= 0.0:
        return np.full(values.size, 1.0 / values.size, dtype=np.float64)

    probs = weights / total
    # Normalize one more time to absorb floating-point drift before np.choice.
    prob_sum = float(probs.sum())
    if not math.isfinite(prob_sum) or prob_sum <= 0.0:
        return np.full(values.size, 1.0 / values.size, dtype=np.float64)
    probs /= prob_sum
    return probs


def sample_actions_from_log_probs(
    log_probs,
    num_samples: int,
    rng: Optional[np.random.Generator] = None,
) -> Tuple[np.ndarray, np.ndarray]:
    """Sample actions *with replacement* according to the old policy.

    Sampling with replacement mirrors GRPO's use of G independent outputs drawn
    from the same old policy. Duplicate byte positions are therefore valid and
    intentional; each occurrence can still yield a different mutant because the
    mutation operator/value is stochastic.
    """
    num_samples = int(num_samples)
    if num_samples <= 0:
        return np.asarray([], dtype=np.int32), np.asarray([], dtype=np.float32)

    probs = probabilities_from_log_probs(log_probs)
    if probs.size == 0:
        return np.asarray([], dtype=np.int32), np.asarray([], dtype=np.float32)

    chooser = rng.choice if rng is not None else np.random.choice
    actions = chooser(probs.size, size=num_samples, replace=True, p=probs)
    actions = np.asarray(actions, dtype=np.int32)

    tiny = np.finfo(np.float32).tiny
    selected_old_log_probs = np.log(np.maximum(probs[actions], tiny)).astype(np.float32)
    return actions, selected_old_log_probs


def group_advantages(rewards, eps: float = EPS) -> np.ndarray:
    """Return GRPO group-relative advantages without divide-by-zero/NaNs."""
    values = np.asarray(rewards, dtype=np.float32).reshape(-1)
    if values.size == 0:
        return np.asarray([], dtype=np.float32)

    # Rewards generated by the fuzzer should be finite. If an unexpected NaN/Inf
    # appears, map it to zero rather than poisoning the entire policy update.
    values = np.nan_to_num(values, nan=0.0, posinf=0.0, neginf=0.0)
    mean = float(values.mean())
    std = float(values.std())
    if not math.isfinite(std) or std <= eps:
        return np.zeros_like(values, dtype=np.float32)

    advantages = (values - mean) / (std + eps)
    return np.nan_to_num(advantages, nan=0.0, posinf=0.0, neginf=0.0).astype(np.float32)


def coverage_delta(pre_group_coverage, new_edge_count, input_edge_hits) -> float:
    """Coverage component of the current GRFuzz reward, safely evaluated.

    All members of a GRPO group should call this with the same
    pre_group_coverage. No division is attempted unless the candidate expands
    coverage and the resulting coverage is strictly positive.
    """
    pre_group_coverage = max(int(pre_group_coverage), 0)
    new_edge_count = max(int(new_edge_count), 0)
    input_edge_hits = max(int(input_edge_hits), 0)
    candidate_coverage = pre_group_coverage + new_edge_count
    if new_edge_count <= 0 or candidate_coverage <= 0:
        return 0.0
    return float(input_edge_hits) / float(candidate_coverage)


def mutation_reward(prior_mutation_count, delta) -> float:
    """Return the manuscript's log(1+MUT_j)+Delta reward safely.

    `prior_mutation_count + 1` represents the current sampled occurrence while
    preserving one common pre-group count for duplicate actions in the group.
    """
    prior_mutation_count = max(int(prior_mutation_count), 0)
    delta = float(delta)
    if not math.isfinite(delta):
        delta = 0.0
    reward = math.log1p(prior_mutation_count + 1) + delta
    return reward if math.isfinite(reward) else 0.0
